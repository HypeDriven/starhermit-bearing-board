// Writes the engine checks' play scripts (tests/native/*.play) from the rules:
// each table is played in node exactly as the game plays it (same content,
// seeds, rules and AI), seat 0 by the steady AI's choices, and every one of
// its commands becomes the input a player would give through the real UI:
// R rolls, the arrow keys move the board cursor (the browser build's board
// mirror: points 1–24, the rail, the off tray) and Enter picks the origin
// and then the target, Pass / Offer Stakes / Accept / Decline are clicked.
// Rival turns are waited for with `until`. Run after a rules, content or AI
// change: node tools/gen-play.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as Rules from '../js/rules.js';
import * as AI from '../js/ai.js';
import * as Content from '../js/content.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SPOTS = Rules.POINTS + 2;

function config(def) {
  return {
    id: def.id, version: def.version || 1, kind: def.kind, ruleset: def.ruleset, players: def.players,
    seed: def.seed >>> 0, options: def.options || {}, goals: def.goals || { win: true },
    layout: def.layout, scriptedDice: def.scriptedDice,
  };
}

/** The UI's choice for a pick of `from` then `to` (main.ts commitMove): a hit first, then the larger die. */
function uiMove(state, m) {
  const same = Rules.legalMoves(state).filter((x) => x.from === m.from && x.to === m.to);
  same.sort((a, b) => (Number(!!b.hit) - Number(!!a.hit)) || (b.die - a.die));
  return same[0];
}

/** The steps that play `def` to its end; `limit` caps the human commands (a safety net). */
export function playTable(def, { limit = 400, stopAfter = Infinity } = {}) {
  let state = Rules.createGame(config(def));
  const lines = [];
  let cursor = null;
  let human = 0;
  const go = (target) => {
    let cur = cursor;
    if (cur === null) { lines.push('key ArrowRight 1'); cur = 0; }
    const n = (target - cur + SPOTS) % SPOTS;
    for (let i = 0; i < n; i++) lines.push('key ArrowRight 1');
    cursor = target;
  };
  while (state.winner < 0) {
    const pending = state.phase === 'cube' ? (state.cube.pending.by + 1) % state.cfg.players : state.active;
    const seat = pending;
    let cmd = AI.aiCommand(state, seat, seat === 0 ? 'steady' : def.ai?.difficulty || 'steady');
    if (!cmd) throw new Error(`${def.id}: no command for seat ${seat}`);
    if (seat === 0) {
      if (human >= stopAfter) break;
      if (++human > limit) throw new Error(`${def.id}: more than ${limit} commands`);
      if (cmd.type === 'roll') { lines.push('until 1200 You to roll', 'frames 2', 'key KeyR 2'); }
      else if (cmd.type === 'double') { lines.push('until 1200 You to roll', 'frames 2', 'click Offer Stakes'); }
      else if (cmd.type === 'pass') { lines.push('until 600 You to move', 'frames 2', 'click Pass'); }
      else if (cmd.type === 'accept' || cmd.type === 'decline') { lines.push('until 1200 Stakes offered', 'frames 10', `click ${cmd.type === 'accept' ? 'Accept' : 'Decline'}`); }
      else if (cmd.type === 'move') {
        cmd = { ...cmd, ...uiMove(state, cmd) };
        lines.push('until 600 You to move');
        go(cmd.from === 'rail' ? Rules.POINTS : cmd.from);
        lines.push('key Enter 1');
        go(cmd.to === 'off' ? Rules.POINTS + 1 : cmd.to);
        lines.push('key Enter 1', 'frames 2');
      }
    }
    const r = Rules.applyCommand(state, { ...cmd, id: `gen-${human}-${lines.length}` });
    if (!r.ok) throw new Error(`${def.id}: ${JSON.stringify(cmd)} refused: ${JSON.stringify(r.events)}`);
    state = r.state;
  }
  return { lines, result: state.result, turns: state.turnNum };
}

function write(name, header, steps) {
  const text = [...header.map((h) => `# ${h}`), ...steps].join('\n') + '\n';
  writeFileSync(join(root, 'tests', 'native', name), text);
  console.log(`tests/native/${name}: ${steps.length} steps`);
}

